def compile_statements(pol: Policy) -> dict[str, str]:
    if pol.purposes.get("training") != "deny":
        return {}
    langs = ["en"]
    js = {j.upper() for j in pol.jurisdictions}
    if js & {"FR", "BE"}:
        langs.append("fr")
    if js & {"DE", "CH"}:
        langs.append("de")
    out = {l: STATEMENTS[l].format(holder=pol.rightsholder, site=pol.site, contact=pol.contact or pol.terms_url or "-") for l in langs}
    notes = [NOTES[j] for j in sorted(js) if j in NOTES]
    if notes:
        out["jurisdiction_notes"] = "\n".join(notes)
    out["disclaimer"] = registry.legal_disclaimer()
    return out


def compile_all(pol: Policy) -> dict[str, str]:
    files = {
        "robots.txt": compile_robots(pol),
        ".well-known/tdmrep.json": compile_tdmrep(pol),
        "headers.json": json.dumps(compile_headers(pol), indent=2) + "\n",
        "nginx.conf": compile_nginx(pol),
        "meta-tags.json": json.dumps(compile_meta(pol), indent=2) + "\n",
        "license.xml": compile_rsl(pol),
        "reservation-statements.json": json.dumps(compile_statements(pol), indent=2, ensure_ascii=False) + "\n",
    }
    manifest = {"generator": GENERATOR, "date": date.today().isoformat(), "policy_digest": pol.digest(),
                "registry_version": registry.registry_version(),
                "files": {k: hashlib.sha256(v.encode()).hexdigest() for k, v in files.items()}}
    files["manifest.json"] = json.dumps(manifest, indent=2) + "\n"
    return files


@dataclass
class Verification:
    ok: bool
    mismatches: list[str]
    dialect_divergences: list[str]
    lints: list[str]


def verify(pol: Policy, robots_txt: str) -> Verification:
    """Check that robots.txt implements the policy for every registry agent, under both parser dialects."""
    rb = robots.parse(robots_txt)
    mism: list[str] = []
    probe = ["/"] + [p.path for p in pol.paths] + list(pol.disallow_all_bots) + ["/some/public/page"]
    for a in registry.agents():
        want = pol.decision(a)
        for p in probe:
            allowed = rb.can_fetch(a.token, p)
            if want == "deny":
                exp = False
            else:
                exp = not (p in pol.disallow_all_bots or p in pol.path_denies(a))
            if allowed != exp:
                mism.append(f"{a.token} {p}: expected {'allow' if exp else 'deny'}, got {'allow' if allowed else 'deny'}")
    tokens = [a.token for a in registry.agents()]
    div = [f"{d.token} {d.path}" for d in dialects.compare(robots_txt, tokens, probe)]
    lints = [f"{l.code}@{l.line}" for l in rb.lints if l.level != "info"]
    return Verification(ok=not mism and not div and not lints, mismatches=mism, dialect_divergences=div, lints=lints)
