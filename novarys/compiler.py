"""Compile one declarative AI-usage policy into every machine-readable format.

A policy states, per purpose (search, ai_answers, user_fetch, training), what
the rightsholder wants. The compiler emits robots.txt (canonical, unambiguous
for RFC 9309 and legacy parsers), TDMRep, HTTP headers, HTML meta tags, an RSL
licence file and jurisdiction-specific reservation statements, then checks its
own output with the auditor.
"""
from __future__ import annotations

import hashlib
import json
from dataclasses import dataclass, field
from datetime import date

from . import dialects, registry, robots

PURPOSES = ("search", "ai_answers", "user_fetch", "training")
DEFAULT_PURPOSES = {"search": "allow", "ai_answers": "allow", "user_fetch": "allow", "training": "deny"}
GENERATOR = "NOVARYS OMNISEARCH policy compiler"


@dataclass
class PathRule:
    path: str
    decisions: dict[str, str] = field(default_factory=dict)  # purpose -> allow|deny
    snippet: str | None = None  # "nosnippet" | "max-snippet:N" (Google AI Overviews / AI Mode)


@dataclass
class Policy:
    site: str
    rightsholder: str
    contact: str = ""
    jurisdictions: list[str] = field(default_factory=lambda: ["EU"])
    purposes: dict[str, str] = field(default_factory=lambda: dict(DEFAULT_PURPOSES))
    agent_overrides: dict[str, str] = field(default_factory=dict)
    disallow_all_bots: list[str] = field(default_factory=list)
    paths: list[PathRule] = field(default_factory=list)
    license_url: str | None = None
    terms_url: str | None = None
    sitemaps: list[str] = field(default_factory=list)

    @classmethod
    def from_dict(cls, d: dict) -> "Policy":
        paths = [PathRule(path=p["path"], decisions={k: p[k] for k in PURPOSES if k in p}, snippet=p.get("snippet")) for p in d.get("paths", [])]
        pol = cls(site=d["site"].rstrip("/"), rightsholder=d["rightsholder"], contact=d.get("contact", ""),
                  jurisdictions=d.get("jurisdictions", ["EU"]), purposes={**DEFAULT_PURPOSES, **d.get("purposes", {})},
                  agent_overrides=d.get("agent_overrides", {}), disallow_all_bots=d.get("disallow_all_bots", []), paths=paths,
                  license_url=d.get("license_url"), terms_url=d.get("terms_url"), sitemaps=d.get("sitemaps", []))
        pol.validate()
        return pol

    def validate(self) -> None:
        for k, v in self.purposes.items():
            if k not in PURPOSES and k not in ("ads", "mixed"):
                raise ValueError(f"unknown purpose '{k}'")
            if v not in ("allow", "deny"):
                raise ValueError(f"purpose '{k}' must be allow|deny")
        for t, v in self.agent_overrides.items():
            if v not in ("allow", "deny"):
                raise ValueError(f"override for '{t}' must be allow|deny")
        for p in self.paths + [PathRule(x) for x in self.disallow_all_bots]:
            if not p.path.startswith("/"):
                raise ValueError(f"path '{p.path}' must start with '/'")

    def decision(self, agent: registry.Agent) -> str:
        for t, v in self.agent_overrides.items():
            if t.lower() == agent.key:
                return v
        if agent.purpose in self.purposes:
            return self.purposes[agent.purpose]
        if agent.purpose == "mixed":
            # an agent of undocumented purpose may train: follow the training decision
            return self.purposes.get("training", "allow")
        return "allow"

    def path_denies(self, agent: registry.Agent) -> list[str]:
        return [p.path for p in self.paths if p.decisions.get(agent.purpose) == "deny"]

    def digest(self) -> str:
        blob = json.dumps(self.__dict__, default=lambda o: o.__dict__, sort_keys=True).encode()
        return hashlib.sha256(blob).hexdigest()


def _signal_values(pol: Policy) -> dict[str, bool]:
    return {"search": pol.purposes.get("search") == "allow",
            "ai-input": pol.purposes.get("ai_answers") == "allow" and pol.purposes.get("user_fetch") == "allow",
            "ai-train": pol.purposes.get("training") == "allow"}


def compile_robots(pol: Policy) -> str:
    sv = _signal_values(pol)
    yn = lambda b: "yes" if b else "no"
    lines = [
        f"# robots.txt generated by {GENERATOR} on {date.today().isoformat()}",
        f"# Rightsholder: {pol.rightsholder}" + (f" <{pol.contact}>" if pol.contact else ""),
        f"# Policy digest (sha256): {pol.digest()}",
        f"# AI training: {pol.purposes.get('training')}; AI answers: {pol.purposes.get('ai_answers')}; user fetches: {pol.purposes.get('user_fetch')}; search: {pol.purposes.get('search')}",
    ]
    if pol.purposes.get("training") == "deny":
        lines.append("# Text and data mining is expressly reserved (Directive (EU) 2019/790, Art. 4(3)); see /.well-known/tdmrep.json")
    lines.append("")
    base = [f"Disallow: {p}" for p in pol.disallow_all_bots]
    # wildcard group
    lines.append("User-agent: *")
    lines.extend(base or ["Allow: /"])
    if pol.purposes.get("training") == "deny":
        lines.append("Content-Usage: train-ai=n")
    lines.append(f"Content-Signal: search={yn(sv['search'])}, ai-input={yn(sv['ai-input'])}, ai-train={yn(sv['ai-train'])}")
    lines.append("")
    # vendor-neutral training token
    if pol.purposes.get("training") == "deny":
        lines += [f"User-agent: {registry.VENDOR_NEUTRAL_TRAINING_TOKEN}", "Disallow: /", ""]
    # named groups, merged by identical rule sets
    groups: dict[tuple[str, ...], list[str]] = {}
    for a in registry.agents():
        if a.token == registry.VENDOR_NEUTRAL_TRAINING_TOKEN:
            continue
        if pol.decision(a) == "deny":
            rules = ("Disallow: /",)
        else:
            extra = [f"Disallow: {p}" for p in pol.path_denies(a)]
            if not extra:
                continue  # identical to the wildcard group: falls back to '*'
            rules = tuple(base + extra)
        groups.setdefault(rules, []).append(a.token)
    for rules, toks in sorted(groups.items(), key=lambda kv: (kv[0] != ("Disallow: /",), kv[1][0].lower())):
        lines += [f"User-agent: {t}" for t in toks]
        lines += list(rules)
        lines.append("")
    if pol.license_url:
        lines.append(f"License: {pol.license_url}")
    for s in pol.sitemaps:
        lines.append(f"Sitemap: {s}")
    return "\n".join(lines).rstrip() + "\n"


def compile_tdmrep(pol: Policy) -> str:
    if pol.purposes.get("training") != "deny":
        return json.dumps([{"location": "/", "tdm-reservation": 0}], indent=2) + "\n"
    entry = {"location": "/", "tdm-reservation": 1}
    if pol.license_url or pol.terms_url:
        entry["tdm-policy"] = pol.license_url or pol.terms_url
    return json.dumps([entry], indent=2) + "\n"


def compile_headers(pol: Policy) -> dict[str, dict[str, str]]:
    """Headers per location ("/" = whole site)."""
    out: dict[str, dict[str, str]] = {"/": {}}
    if pol.purposes.get("training") == "deny":
        out["/"]["tdm-reservation"] = "1"
        if pol.license_url or pol.terms_url:
            out["/"]["tdm-policy"] = pol.license_url or pol.terms_url
        out["/"]["Content-Usage"] = "train-ai=n"
    for p in pol.paths:
        if p.snippet:
            out.setdefault(p.path, {})["X-Robots-Tag"] = p.snippet
    return out


def compile_nginx(pol: Policy) -> str:
    h = compile_headers(pol)
    lines = [f"# nginx snippet generated by {GENERATOR}"]
    for loc, headers in h.items():
        if not headers:
            continue
        lines.append(f"location {'/' if loc == '/' else '^~ ' + loc} {{" if loc != "/" else "# site-wide (put inside the server block)")
        for k, v in headers.items():
            lines.append(f"    add_header {k} \"{v}\" always;")
        if loc != "/":
            lines.append("}")
    return "\n".join(lines) + "\n"


def compile_meta(pol: Policy) -> dict[str, list[str]]:
    out: dict[str, list[str]] = {"/": []}
    if pol.purposes.get("training") == "deny":
        out["/"].append('<meta name="tdm-reservation" content="1">')
        if pol.license_url or pol.terms_url:
            out["/"].append(f'<meta name="tdm-policy" content="{pol.license_url or pol.terms_url}">')
    for p in pol.paths:
        if p.snippet:
            out.setdefault(p.path, []).append(f'<meta name="robots" content="{p.snippet}">')
    return out


def compile_rsl(pol: Policy) -> str:
    sv = _signal_values(pol)
    permits, prohibits = [], []
    (permits if sv["search"] else prohibits).append("search")
    (permits if pol.purposes.get("ai_answers") == "allow" else prohibits).append("ai-input")
    (permits if sv["ai-train"] else prohibits).append("ai-train")
    xml = ['<?xml version="1.0" encoding="UTF-8"?>',
           f"<!-- RSL licence generated by {GENERATOR}; check element names against the RSL 1.0 specification (rslstandard.org) -->",
           '<rsl xmlns="https://rslstandard.org/rsl">',
           f'  <content url="{pol.site}/">',
           "    <license>"]
    if permits:
        xml.append(f'      <permits type="usage">{" ".join(permits)}</permits>')
    if prohibits:
        xml.append(f'      <prohibits type="usage">{" ".join(prohibits)}</prohibits>')
    if pol.terms_url:
        xml.append(f"      <terms>{pol.terms_url}</terms>")
    xml += ["    </license>", "  </content>", "</rsl>"]
    return "\n".join(xml) + "\n"


